import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const webRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.resolve(webRoot, "..");
const skillRoot = path.join(repoRoot, ".agents", "skills", "drama-video-director");
const sourcePath = path.join(skillRoot, "SKILL.md");
const outputPath = path.join(webRoot, "src", "lib", "server", "agent-skills", "drama-video-director.generated.ts");
const manifestPath = path.join(skillRoot, "manifest.json");
const source = readFileSync(sourcePath, "utf8");
const normalized = source.replace(/^\uFEFF/, "").trim();
const end = normalized.indexOf("\n---", 3);
const frontmatter = end >= 0 ? parse(normalized.slice(3, end).trim()) || {} : {};
const body =
    end >= 0
        ? normalized
              .slice(end + "\n---".length)
              .replace(/^\r?\n/, "")
              .trim()
        : normalized;
const sourceContentHash = createHash("sha256").update(source, "utf8").digest("hex");
const sections = {
    common: extractSection(body, "共同前置审计"),
    cinematography: extractSection(body, "摄影与画面"),
    performance: extractSection(body, "表演与节奏"),
    staticFrame: extractSection(body, "静态帧适配器"),
    video: extractSection(body, "视频适配器"),
    package: extractSection(body, "制作包适配器"),
    gates: extractSection(body, "门禁分层"),
    externalCodex: extractSection(body, "外部 Codex 调用"),
};

const skill = {
    id: String(frontmatter.name || "drama-video-director"),
    name: String(frontmatter.displayName || frontmatter.name || "短剧视频导演"),
    description: String(frontmatter.description || ""),
    sourcePath: "SKILL.md",
    sourceVersion: String(frontmatter.version || "current"),
    sourceContentHash,
    enabled: true,
    workspaces: Array.isArray(frontmatter.workspaces) ? frontmatter.workspaces.map(String) : ["video", "drama"],
    action: String(frontmatter.action || "generate"),
    requiresReference: Boolean(frontmatter.requiresReference),
    keywords: Array.isArray(frontmatter.keywords) ? frontmatter.keywords.map(String) : [],
    instructions: body,
    sections,
};

const output = `/* Generated by scripts/compile-drama-video-director-skill.mjs. Do not edit manually. */
export type DramaDirectorSurface = "package" | "static-frame" | "video" | "external-codex";

export const DRAMA_VIDEO_DIRECTOR_SKILL = ${JSON.stringify(skill, null, 4)} as const;

const SURFACE_SECTIONS: Record<DramaDirectorSurface, string[]> = {
    package: ["common", "cinematography", "performance", "package", "gates"],
    "static-frame": ["common", "cinematography", "performance", "staticFrame", "gates"],
    video: ["common", "cinematography", "performance", "video", "gates"],
    "external-codex": ["common", "cinematography", "performance", "package", "staticFrame", "video", "gates", "externalCodex"],
};

export function resolveDramaDirectorInstructions(surface: DramaDirectorSurface) {
    return SURFACE_SECTIONS[surface].map((section) => DRAMA_VIDEO_DIRECTOR_SKILL.sections[section as keyof typeof DRAMA_VIDEO_DIRECTOR_SKILL.sections]).filter(Boolean).join("\\n\\n");
}

export function dramaDirectorSourceManifest() {
    return { id: DRAMA_VIDEO_DIRECTOR_SKILL.id, sourceVersion: DRAMA_VIDEO_DIRECTOR_SKILL.sourceVersion, sourceContentHash: DRAMA_VIDEO_DIRECTOR_SKILL.sourceContentHash } as const;
}
`;

writeFileSync(outputPath, output, "utf8");
writeFileSync(
    manifestPath,
    `${JSON.stringify(
        {
            id: skill.id,
            name: skill.name,
            sourceVersion: skill.sourceVersion,
            sourceContentHash,
            runtimeModule: "web/src/lib/server/agent-skills/drama-video-director.generated.ts",
            execution: "planning-only; provider submission remains in VOZEB PRO task runtime",
        },
        null,
        2,
    )}\n`,
    "utf8",
);

function extractSection(value, heading) {
    const lines = value.split(/\r?\n/u);
    const start = lines.findIndex((line) => line.trim() === `## ${heading}`);
    if (start < 0) return "";
    const content = [];
    for (const line of lines.slice(start + 1)) {
        if (/^##\s+/u.test(line.trim())) break;
        content.push(line);
    }
    return content.join("\n").trim();
}

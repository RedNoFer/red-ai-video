import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const webRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.resolve(webRoot, "..");
const sourcePath = path.join(repoRoot, ".agents", "skills", "drama-image", "SKILL.md");
const outputPath = path.join(webRoot, "src", "lib", "drama-image-skill.generated.ts");
const source = readFileSync(sourcePath, "utf8");
const normalized = source.replace(/^\uFEFF/, "").trim();
const end = normalized.indexOf("\n---", 3);
const frontmatter = end >= 0 ? parse(normalized.slice(3, end).trim()) || {} : {};
const body = end >= 0 ? normalized.slice(end + "\n---".length).replace(/^\r?\n/, "").trim() : normalized;
const sourceContentHash = createHash("sha256").update(source, "utf8").digest("hex");
const promptRules = extractSection(body, "生成规则");
const refinementRules = extractSection(body, "调整规则");

writeFileSync(
    outputPath,
    `/* Generated by scripts/compile-drama-image-skill.mjs. Do not edit manually. */\nexport const DRAMA_ASSET_IMAGE_SKILL = ${JSON.stringify(
        {
            id: String(frontmatter.name || "drama-asset-image-director"),
            name: String(frontmatter.displayName || frontmatter.name || "drama-asset-image-director"),
            description: String(frontmatter.description || ""),
            sourcePath: "SKILL.md",
            sourceVersion: String(frontmatter.version || "current"),
            sourceContentHash,
            license: String(frontmatter.license || "MIT"),
            enabled: true,
            workspaces: Array.isArray(frontmatter.workspaces) ? frontmatter.workspaces.map(String) : ["image", "drama"],
            action: String(frontmatter.action || "generate"),
            requiresReference: Boolean(frontmatter.requiresReference),
            defaultConfig: frontmatter.defaultConfig && typeof frontmatter.defaultConfig === "object" ? frontmatter.defaultConfig : {},
            keywords: Array.isArray(frontmatter.keywords) ? frontmatter.keywords.map(String) : [],
            instructions: body,
            promptRules,
            refinementRules,
        },
        null,
        4,
    )} as const;\n`,
    "utf8",
);

function extractSection(value, heading) {
    const lines = value.split(/\r?\n/u);
    const start = lines.findIndex((line) => line.trim() === `## ${heading}`);
    if (start < 0) return "";
    const content = [];
    for (const line of lines.slice(start + 1)) {
        if (/^##\s+/u.test(line.trim())) break;
        content.push(line);
    }
    return content.join("\n").trim();
}

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import prettier from "prettier";
import { hashSkillContent } from "./skill-content-hash.mjs";

const webRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.resolve(webRoot, "..");
const templateSourcePath = path.join(repoRoot, "docs", "drama-production-package-v1-template.md");
const skillRoot = path.join(repoRoot, ".agents", "skills", "drama-video-director");
const skillSourcePath = path.join(skillRoot, "SKILL.md");
const packageSpecPath = path.join(repoRoot, "docs", "drama-production-package-v1.md");
const contractRuntimePath = path.join(webRoot, "src", "lib", "server", "drama-production-package-contract.generated.ts");
const outputPath = path.join(webRoot, "public", "drama-production-package-v1-template.md");

const templateSource = readFileSync(templateSourcePath, "utf8");
const skillSource = readFileSync(skillSourcePath, "utf8");
const packageSpec = readFileSync(packageSpecPath, "utf8");
const skillVersion = skillSource.match(/^version:\s*(.+)$/mu)?.[1]?.trim() || "current";
const skillHash = hashSkillContent(skillRoot);
const packageSpecHash = sha256(packageSpec);
const contractBlock = extractSection(packageSpec, "版本化契约块");
const contractHash = sha256(contractBlock);
const contractVersion = contractBlock.match(/version:\s*([0-9.]+)/u)?.[1] || "1.0.0";
const packageAuthoringRules = extractSection(packageSpec, "Agent 运行时规则");
if (!packageAuthoringRules) throw new Error("制作包规范缺少 Agent 运行时规则章节");
const externalGateRules = extractSection(packageSpec, "外部独立生成门禁");
if (!externalGateRules) throw new Error("制作包规范缺少外部独立生成门禁章节");
const externalGateRegister = extractMarkdownSubsection(externalGateRules, "门禁登记表");
if (!externalGateRegister) throw new Error("制作包规范缺少外部门禁登记表");
const packageRulesHash = sha256(packageAuthoringRules);
const packageChapterHeadings = extractPackageChapterHeadings(packageSpec);
const gateCodes = extractContractGateCodes(contractBlock);
const codexWorkOrderRules = [
    "外部 Codex 只能在项目 GPT 明确超时、任务已结束且用户主动确认后使用。",
    "Codex 只返回 mode=package 的 authoring draft；最终校验、序列化和导入仍由 executeDramaScriptRun 完成。",
    "提交时必须回传当前 workOrderId、契约/Skill 版本与内容哈希，以及模板/TXT/参考素材的 alias、role、顺序和内容哈希。",
    extractSection(packageSpec, "外部 Codex 工作单协议"),
]
    .filter(Boolean)
    .join("\n");
if (packageChapterHeadings.length !== 13) throw new Error(`制作包规范必须定义 13 个一级章节，当前为 ${packageChapterHeadings.length} 个`);
if (gateCodes.length < 1) throw new Error("制作包规范未定义硬门禁代码");

const replacements = {
    "{{DRAMA_VIDEO_DIRECTOR_VERSION}}": skillVersion,
    "{{DRAMA_VIDEO_DIRECTOR_HASH}}": skillHash,
    "{{DRAMA_PACKAGE_SPEC_HASH}}": packageSpecHash,
    "{{DRAMA_PACKAGE_CONTRACT_VERSION}}": contractVersion,
    "{{DRAMA_PACKAGE_CONTRACT_HASH}}": contractHash,
    "{{DRAMA_PACKAGE_RULES_HASH}}": packageRulesHash,
    "{{DRAMA_PACKAGE_EXTERNAL_GATE_RULES}}": externalGateRegister,
    "{{DRAMA_VIDEO_DIRECTOR_STATIC_FRAME_RULES}}": `当前静态帧规则由编译后的 drama-video-director Skill 提供（Skill hash：${skillHash}）；模板仅保留字段位置。`,
};
const template =
    Object.entries(replacements)
        .reduce((value, [token, replacement]) => value.replaceAll(token, replacement), templateSource)
        .trimEnd() + "\n";
if (/\{\{[A-Z0-9_]+\}\}/u.test(template)) throw new Error("制作包模板存在未替换的同步标记");
for (const heading of packageChapterHeadings) {
    if (!new RegExp(`^##\\s+[^\\n]*${escapeRegExp(heading)}`, "mu").test(template)) throw new Error(`制作包模板缺少规范章节：${heading}`);
}
const packageContractMarkers = ["imagePrompt", "framePlan.start.source", "framePlan.end.required", "framePlan.referenceManifest", "dramaticFunction", "backgroundNpcPolicy"];
const templateContractMarkers = ["## 规范对象（机器导入必填）", "```drama-production-package", '"schemaVersion": 1', '"episodes"'];
for (const marker of packageContractMarkers) {
    if (!packageAuthoringRules.includes(marker)) throw new Error(`制作包规范缺少规范字段：${marker}`);
    if (!template.includes(marker)) throw new Error(`制作包模板缺少规范字段：${marker}`);
}
for (const marker of templateContractMarkers) {
    if (!template.includes(marker)) throw new Error(`制作包模板缺少机器导入字段：${marker}`);
}

const prettierConfig = (await prettier.resolveConfig(contractRuntimePath)) || {};
const formattedTemplate = await prettier.format(template, { ...prettierConfig, filepath: outputPath, parser: "markdown" });
writeFileSync(outputPath, formattedTemplate, "utf8");
const formattedContract = await prettier.format(
    `/* Generated by scripts/compile-drama-production-package-template.mjs. Do not edit manually. */
export const COMPILED_DRAMA_PACKAGE_CONTRACT = ${JSON.stringify({ id: "vozeb-drama-production-package-v1", version: contractVersion, contentHash: contractHash }, null, 4)} as const;
export const COMPILED_DRAMA_PACKAGE_SPEC_HASH = ${JSON.stringify(packageSpecHash)} as const;
export const COMPILED_DRAMA_PACKAGE_TEMPLATE_SOURCE_HASH = ${JSON.stringify(sha256(templateSource))} as const;
export const COMPILED_DRAMA_PACKAGE_TEMPLATE_SOURCE = ${JSON.stringify(templateSource)} as const;
export const COMPILED_DRAMA_PACKAGE_RULES_HASH = ${JSON.stringify(packageRulesHash)} as const;
export const COMPILED_DRAMA_PACKAGE_AUTHORING_RULES = ${JSON.stringify(packageAuthoringRules)} as const;
export const COMPILED_DRAMA_PACKAGE_EXTERNAL_GATE_RULES = ${JSON.stringify(externalGateRules)} as const;
export const COMPILED_DRAMA_PACKAGE_SECTION_TITLES = ${JSON.stringify(packageChapterHeadings)} as const;
export const COMPILED_DRAMA_PACKAGE_GATE_CODES = ${JSON.stringify(gateCodes)} as const;
export const COMPILED_DRAMA_CODEX_WORK_ORDER_RULES = ${JSON.stringify(codexWorkOrderRules)} as const;
`,
    { ...prettierConfig, filepath: contractRuntimePath, parser: "typescript" },
);
writeFileSync(contractRuntimePath, formattedContract, "utf8");

function sha256(value) {
    return createHash("sha256").update(value, "utf8").digest("hex");
}

function extractSection(value, heading) {
    const lines = value.replace(/^---[\s\S]*?---\r?\n/u, "").split(/\r?\n/u);
    const start = lines.findIndex((line) => line.trim() === `## ${heading}`);
    if (start < 0) return "";
    const content = [];
    for (const line of lines.slice(start + 1)) {
        if (/^##\s+/u.test(line.trim())) break;
        content.push(line);
    }
    return content.join("\n").trim();
}

function extractMarkdownSubsection(value, heading) {
    const lines = value.split(/\r?\n/u);
    const start = lines.findIndex((line) => line.trim() === `### ${heading}`);
    if (start < 0) return "";
    const content = [];
    for (const line of lines.slice(start + 1)) {
        if (/^###\s+/u.test(line.trim())) break;
        content.push(line);
    }
    return content.join("\n").trim();
}

function extractPackageChapterHeadings(value) {
    const section = extractSection(value, "固定章节顺序");
    return [...section.matchAll(/^\d+\.\s+([^：:]+)[：:]/gmu)].map((match) => match[1].trim());
}

function extractContractGateCodes(value) {
    return [...value.matchAll(/^\s+-\s+([A-Z][A-Z_]+)\s*$/gmu)].map((match) => match[1]);
}

function escapeRegExp(value) {
    return value.replace(/[.*+?^${}()|[\]\\]/gu, "\\$&");
}

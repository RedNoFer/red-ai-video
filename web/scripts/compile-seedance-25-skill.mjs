function splitFrontmatter(value) {
    const normalized = value.replace(/^\uFEFF/, "").trim();
    if (!normalized.startsWith("---")) return { frontmatter: {}, body: normalized };
    const end = normalized.indexOf("\n---", 3);
    if (end < 0) return { frontmatter: {}, body: normalized };
    return { frontmatter: parse(normalized.slice(3, end).trim()) || {}, body: normalized.slice(end + "\n---".length).replace(/^\r?\n/, "") };
}

function extractModeReferences(value) {
    const names = ["basic-multimodal", "timestamp-30s", "long-video", "video-extension", "video-edit", "clay-renderer", "seamless-transition", "multi-grid-storyboard"];
    return Object.fromEntries(names.map((name) => [name, extractSection(value, name)]));
}

function extractSection(value, name) {
    const lines = value.split(/\r?\n/u);
    const heading = `## ${name}`;
    const start = lines.findIndex((line) => line.trim() === heading);
    if (start < 0) return "";
    const content = [];
    for (const line of lines.slice(start + 1)) {
        if (/^##\s+/u.test(line.trim())) break;
        content.push(line);
    }
    return content.join("\n").trim();
}
